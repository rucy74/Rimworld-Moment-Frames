    /// <summary>The existing settings, grouped for the native options window.
    /// Metadata comes from the accepted settings prototype; reads and writes use
    /// the existing fields and do not change values while drawing or searching.</summary>
    internal static class SettingsCatalog
    {
        internal enum SettingKind { Toggle, Range, Select, Text, Action }

        internal sealed class Category
        {
            internal string Id, LabelKey, HintKey;
            internal Group[] Groups;
            internal string Label => LabelKey.Translate();
            internal string Title => Label;
            internal string Hint => HintKey.Translate();
        }

        internal sealed class Group
        {
            internal string Id, Category, LabelKey;
            internal string Label => LabelKey.Translate();
        }

        internal sealed class Option
        {
            internal object Value;
            internal string LabelKey, LiteralLabel, SourceLabelKey;
            internal string Label => LabelKey == null ? LiteralLabel : LabelKey.Translate().ToString();
        }

        internal sealed class Setting
        {
            internal string Id, Field, Category, Group, LabelKey, HelpKey;
            internal string SourceLabelKey, SourceHelpKey, UnitKey, Preview;
            internal SettingKind Kind;
            internal bool InlineOptions;
            internal object Default;
            internal float Min, Max, Step;
            internal Option[] Options;
            internal string ConditionField, DisabledReasonKey;
            internal bool ConditionNotEquals;
            internal object ConditionValue;
            internal Func<MomentFramesSettings, object> Read;
            internal Action<MomentFramesSettings, object> Write;
            internal Func<MomentFramesSettings, bool> Condition;
            internal string Label => LabelKey.Translate();
            internal string Help => HelpKey.Translate();
            internal string DisabledReason => DisabledReasonKey == null ? "" : DisabledReasonKey.Translate().ToString();
            internal object Get(MomentFramesSettings settings) => Read == null ? null : Read(settings);
            internal void Set(MomentFramesSettings settings, object value) { Write?.Invoke(settings, value); }
            internal bool Enabled(MomentFramesSettings settings) => Condition == null || Condition(settings);
        }

